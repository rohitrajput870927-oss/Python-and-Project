add=lambda a,b : a+b
print("Addition of two number",add(5,6))

add=lambda a,b,c,d : a+b+c+d
print("Addition of four no.",add(1,2,3,4))

mul=lambda a,b : a*b
print("Multiply two number",mul(2,6))

mul=lambda a,b,c,d:a*b*c*d
print(mul(10,4,6,3))

div=lambda a,b:a/b
print(div(100,10))

mix=lambda a,b,c,d,e:(a+b*c-d)/e
